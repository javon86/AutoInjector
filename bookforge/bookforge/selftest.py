class StepFailed(Exception):
    def __init__(self, detail: str, fix: str | None = None):
        super().__init__(detail)
        self.detail, self.fix = detail, fix


class StepSkipped(Exception):
    def __init__(self, detail: str, fix: str | None = None):
        super().__init__(detail)
        self.detail, self.fix = detail, fix


def expect(cond, detail: str, fix: str | None = None):
    if not cond:
        raise StepFailed(detail, fix)


def _problems(resp: dict) -> str:
    errs = "; ".join(f"{e['code']} at {e.get('path') or '/'}: {e.get('message') or ''}" for e in resp.get("errors", []))
    finds = "; ".join(f"{f['rule_id']} ({f['decision']}): {f['message']}" for f in resp.get("findings", [])
                      if f.get("severity") in ("MAJOR", "BLOCKING") and f.get("decision") != "PASS")
    return (errs or finds or f"status {resp.get('status')}")[:600]


def _non_pass(resp: dict) -> str:
    return "; ".join(f"{f['rule_id']} {f['decision']}: {f['message']}" for f in resp["result"]["findings"]
                     if f["decision"] != "PASS")[:600]


def fact(s, p, v, a="FACT"):
    return {"subject_id": s, "predicate": p, "value": v, "assertion_type": a, "effective_from": None,
            "effective_to": None, "source_refs": []}


