# ---------------------------------------------------------------------- AI gating
class SelfTestProviders(ProviderRegistry):
    """The author's real AI slots, gated: AI is reachable only while an AI step runs and only
    through slots that passed the self-test's health check. Everything else sees no slot, so
    manual steps never send anything anywhere."""

    def __init__(self, base: ProviderRegistry):
        self._base = base
        super().__init__(base.store, base.secret_path)
        self.ai_on = False
        self.ready: set[str] = set()

    @property
    def test_adapter(self):
        return getattr(self._base, "test_adapter", None)

    @test_adapter.setter
    def test_adapter(self, value):  # the base registry owns it
        pass

    def eligible(self, project_id, capability, needed_tokens, operation=None):
        if not self.ai_on:
            return []
        return [s for s in super().eligible(project_id, capability, needed_tokens, operation)
                if s["slot_id"] in self.ready]


def slot_summary(slot: dict) -> dict:
    """Secret-free description of one slot (never the key itself)."""
    out = {"slot_id": slot["slot_id"], "adapter": slot["adapter_id"], "connected": slot["connected"],
           "credentials_saved": bool(slot.get("has_credentials")), "roles": list(slot.get("roles") or [])}
    if slot["adapter_id"] == "autoinjector":
        out.update(site=slot.get("site"), bridge_url=slot.get("bridge_url"))
    elif slot["adapter_id"] == "anthropic":
        out.update(model=slot.get("model"))
    return out


