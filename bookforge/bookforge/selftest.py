"""BookForge self-test ("Test everything"): a real run of the whole program, step by step.

It creates its own clearly named project ("Self-test <date time>") in the normal store, so the
author can open and inspect every record afterwards, and drives the real code path only:
every step goes through ``engine.dispatch`` (plus the C-owned ``extract_event_bundle`` resume
step for manual story events), the records it writes are AUTHORITATIVE, and exported bytes
are re-parsed with the independent H09 parsers in ``h_checks``.

Creative work uses manual candidates by default ("MANUAL (no AI)"). With ``use_ai`` the
creative steps that have an AI path (B01 premise, C02 chapter prose + event extraction) are
sent to the configured AI slots for real, after a health check of each slot. A slot that is
not set up or not reachable makes the AI step SKIPPED with the exact reason and fix, and the
book slice continues manually.

Each step records id, plain-English title, PASS/FAIL/SKIPPED, detail, a how-to-fix tip,
elapsed ms and the records it created. One failure never stops independent steps; steps that
need a failed step are SKIPPED with "needs step X".

The documented report goes to ``<data_dir>/reports/selftest-<stamp>.md`` and ``.json``. It
never contains secrets, connection keys, or AI prompts/replies (only lengths and hashes).

CLI: ``python -m bookforge selftest [--data-dir D] [--ai]``.
"""
