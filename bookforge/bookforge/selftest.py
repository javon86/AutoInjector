    # ------------------------------------------------------------ progress
    def snapshot(self) -> dict:
        done = len(self.results)
        return {"project_id": self.project_id, "project_name": self.project_name, "use_ai": self.use_ai,
                "current_step": self.current, "done": done, "total": len(self.steps),
                "steps": [{k: v for k, v in r.items()} for r in self.results],
                "pending": [{"id": s["id"], "title": s["title"]} for s in self.steps[done:]]}

    def _emit(self):
        if self.on_progress:
            try:
                self.on_progress(self.snapshot())
            except Exception:  # noqa: BLE001 - progress display must never break the run
                pass

    # ------------------------------------------------------------ main loop
    def run(self) -> dict:
        t_all = time.monotonic()
        status_by_id: dict[str, str] = {}
        titles = {s["id"]: s["title"] for s in self.steps}
        for step in self.steps:
            self.current = f"{step['id']} {step['title']}"
            self._emit()
            res = {"id": step["id"], "title": step["title"], "status": None, "detail": "", "fix": None,
                   "elapsed_ms": 0, "records": [], "ai_step": step["ai"], "about": step["about"]}
            missing = [n for n in step["needs"] if status_by_id.get(n) != PASS]
            t0 = time.monotonic()
            if missing:
                res.update(status=SKIPPED, detail="needs step " + ", ".join(f"{n} ({titles[n]})" for n in missing)
                           + " which did not pass",
                           fix="Fix the earlier failed step first; this step runs automatically after it passes.")
            else:
                self._records = res["records"]
                try:
                    out = step["fn"]()
                    res.update(status=PASS, detail=out or "ok")
                except StepSkipped as exc:
                    res.update(status=SKIPPED, detail=exc.detail, fix=exc.fix)
                except StepFailed as exc:
                    res.update(status=FAIL, detail=exc.detail, fix=exc.fix or BUG_FIX)
                except Exception as exc:  # noqa: BLE001 - a crash in one step must not stop the run
                    tb = traceback.extract_tb(exc.__traceback__)[-1]
                    res.update(status=FAIL, detail=f"unexpected error {type(exc).__name__}: {str(exc)[:300]} "
                               f"(at {Path(tb.filename).name}:{tb.lineno})", fix=BUG_FIX)
                finally:
                    self._records = None
                    self.providers.ai_on = False
            res["elapsed_ms"] = int((time.monotonic() - t0) * 1000)
            status_by_id[step["id"]] = res["status"]
            self.results.append(res)
            self._emit()
        self.current = None
        self.elapsed_ms = int((time.monotonic() - t_all) * 1000)
        report = self.build_report()
        self.write_report(report)
        self._emit()
        return report

    # ================================================================ kernel steps
    def k_contracts(self):
        c = self.engine.contracts
        expect(len(c.operation_ids) == 142, f"expected 142 operations, found {len(c.operation_ids)}")
        expect(isinstance(c.package_sha256, str) and len(c.package_sha256) == 64, "package hash missing")
        for op in ("A01", "C02", "G11", "H10", "K09"):
            schema = c.schema(op)
            expect(schema and "OUTPUT" in schema.get("$defs", {}), f"schema for {op} is missing")
        return (f"{len(c.operation_ids)} operations, contract {CONTRACT_VERSION} / {CLOSURE_REVISION}, "
                f"package sha256 {c.package_sha256}")

    def p_project(self):
        old = [r["project_id"] for r in self.store.query("SELECT project_id, settings FROM projects WHERE archived=0")
               if '"selftest": true' in (r["settings"] or "")]
        self.project_id = self.engine.bootstrap_project(
            self.principal, self.project_name, settings={"selftest": True},
            features={"character_arcs": False}, release_profiles=list(RELEASE_PROFILES))
        if old:  # BF-19: earlier self-test books are archived (hidden, kept), so only the newest one is listed
            with self.store.transaction() as tx:
                for o in old:
                    tx.conn.execute("UPDATE projects SET archived=1 WHERE project_id=?", (o,))
        return f"project '{self.project_name}' ({self.project_id}) with release profiles {', '.join(RELEASE_PROFILES)}"

    def _count(self):
        return self.store.query_one("SELECT COUNT(*) c FROM records WHERE project_id=?", (self.project_id,))["c"]

    def k_schema(self):
        before = self._count()
        bad = self.create("A01", {"concept": 12345})
        codes = {e["code"] for e in bad["errors"]}
        expect(bad["status"] == "REJECTED" and codes & {"INVALID_INPUT", "MISSING_INPUT"},
               f"invalid A01 payload was not rejected (status {bad['status']}, errors {sorted(codes)})")
        missing = self.create("B01", {})
        expect(missing["errors"], "a CREATE without required fields was accepted")
        expect(self._count() == before, "a rejected request stored a record")
        return (f"wrong type rejected with {sorted(codes)} at {bad['errors'][0]['path']}; missing fields rejected "
                f"with {missing['errors'][0]['code']}; nothing stored")

    def k_idempotent(self):
        req = self.request("A01", "CREATE", payload={"concept": "Self-test probe: idempotency"},
                           idempotency_key=f"selftest-{self.project_id}-idem")
        a = self.engine.dispatch(req, self.principal)
        b = self.engine.dispatch(req, self.principal)
        self._track(a)
        expect(a["status"] == "DRAFT", f"probe CREATE failed: {_problems(a)}")
        expect(a["output_refs"] == b["output_refs"], "the replay produced a different record")
        n = self.store.query_one("SELECT COUNT(*) c FROM records WHERE project_id=? AND record_id=?",
                                 (self.project_id, a["output_refs"][0]["record_id"]))["c"]
        expect(n == 1, f"replay stored {n} copies")
        c = self.engine.dispatch(dict(req, payload={"concept": "different"}), self.principal)
        expect(c["errors"] and c["errors"][0]["code"] == "IDEMPOTENCY_CONFLICT",
               "reusing the key with different content was not refused")
        return "same request twice -> same record (1 copy); same key with other content -> IDEMPOTENCY_CONFLICT"

