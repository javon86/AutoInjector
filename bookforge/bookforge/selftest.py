    def ai_health(self):
        if not self.use_ai:
            raise StepSkipped("not requested: 'Use my AI slots' was off, so nothing was sent to any AI",
                              "Tick 'Use my AI slots too' (or pass --ai) to test your AI connections as well.")
        lines, ready = [], set()
        slots = self.base_providers.slots()
        fake = getattr(self.base_providers, "test_adapter", None) is not None
        for s in slots:
            info = slot_summary(s)
            sid, adapter = s["slot_id"], s["adapter_id"]
            if adapter == "none":
                info.update(state="NOT_SET_UP", message="not set up")
            elif adapter == "manual":
                info.update(state="MANUAL", message="manual adapter (you write candidates; no AI)")
            elif adapter == "autoinjector":
                hres = self.base_providers.health_check(sid)
                ok = bool(hres.get("ok"))
                info.update(state="READY" if ok else "ERROR", message=hres.get("message"), error=hres.get("error"),
                            site_ready=hres.get("site_ready"), site_busy=hres.get("site_busy"))
                if ok:
                    ready.add(sid)
            elif adapter == "anthropic":
                if fake:
                    info.update(state="READY", message="test adapter")
                    ready.add(sid)
                elif importlib.util.find_spec("anthropic") is None:
                    info.update(state="ERROR", message="the 'anthropic' package is not installed "
                                "(run: python -m pip install anthropic)")
                elif not s.get("has_credentials"):
                    info.update(state="ERROR", message="no API key saved and ANTHROPIC_API_KEY is not set")
                else:
                    info.update(state="READY", message="API key present (no free live check exists; the first "
                                "AI step is the real test)")
                    ready.add(sid)
            self.ai_slots.append(info)
            lines.append(f"{sid} [{adapter}{'/' + str(s.get('site')) if adapter == 'autoinjector' else ''}]: "
                         f"{info['state']} - {info['message']}")
        self.providers.ready = ready
        if not ready:
            reason = "no AI slot is ready: " + "; ".join(lines)
            self.ai_problem = (reason, AI_SETUP_FIX)
            raise StepSkipped(reason + ". The creative steps fall back to MANUAL (no AI).", AI_SETUP_FIX)
        return f"{len(ready)} slot(s) ready: " + "; ".join(lines)

